from pydantic import BaseModel, Field


class TokenPair(BaseModel):
    access_token: str
    refresh_token: str
    token_type: str = "bearer"
    is_new_user: bool = False
    needs_onboarding: bool = True


class RefreshTokenRequest(BaseModel):
    refresh_token: str = Field(min_length=1)


class GoogleExchangeRequest(BaseModel):
    id_token: str = Field(min_length=1, max_length=8192)
    # Do not default to account creation: a stale client must not accidentally
    # create an account from the existing-account sign-in path.
    create_account: bool


class AppleExchangeRequest(BaseModel):
    id_token: str = Field(min_length=1, max_length=8192)
    nonce: str = Field(min_length=16, max_length=256)
    # Do not default to account creation: a stale client must not accidentally
    # create an account from the existing-account sign-in path.
    create_account: bool


class LineExchangeRequest(BaseModel):
    id_token: str = Field(min_length=1, max_length=8192)
    # Generated by the LINE SDK for this single authorization attempt and
    # verified by LINE along with the signed token.
    nonce: str = Field(min_length=1, max_length=256)
    # Do not default to account creation: a stale client must not accidentally
    # create an account from the existing-account sign-in path.
    create_account: bool


class KakaoExchangeRequest(BaseModel):
    # A native Kakao SDK access token. It is only used once: the server sends
    # it to Kakao's token-info API and then issues a separate MOHANO session.
    access_token: str = Field(min_length=1, max_length=8192)
    # Do not default to account creation: a stale client must not accidentally
    # create an account from the existing-account sign-in path.
    create_account: bool


class LocalTestLoginRequest(BaseModel):
    """Local browser testing only; never enable this authentication in production."""

    username: str = Field(min_length=1, max_length=40)
    password: str = Field(min_length=1, max_length=128)
